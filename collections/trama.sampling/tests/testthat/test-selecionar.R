test_that("AAS: n exato, pesos N/n, e a semente reproduz sem mexer na do usuário", {
  f <- ex("fazendas")
  set.seed(42); antes <- .Random.seed
  a <- tr_sampling_srs(f, n = 150L, .seed = 7L)
  expect_identical(.Random.seed, antes)
  b <- tr_sampling_srs(f, n = 150L, .seed = 7L)
  expect_identical(a$dados$fazenda, b$dados$fazenda)
  expect_false(identical(a$dados$fazenda, tr_sampling_srs(f, n = 150L, .seed = 8L)$dados$fazenda))
  expect_equal(nrow(a$dados), 150L)
  expect_false(anyDuplicated(a$dados$fazenda) > 0)
  expect_equal(unique(a$dados$peso_amostral), 2400 / 150)
  expect_equal(nrow(tr_sampling_srs(f, fracao = 0.05)$dados), 120L)
  expect_error(tr_sampling_srs(f), class = "tr_sampling_error_blank_param")
  expect_error(tr_sampling_srs(f, n = 3000L), class = "tr_sampling_error_too_large")
  expect_no_error(tr_sampling_srs(f[1:10, ], n = 30L, reposicao = TRUE))
})

